function gcd(a: number, b: number): number {
  return b === 0 ? a : gcd(b, a % b);
}

/** Passo coprimo com o tamanho da biblioteca: percorre todas as frases antes de repetir e espalha as categorias */
const STEP = (() => {
  const n = MOTIVATIONS.length;
  let step = Math.round(n * 0.618);
  while (gcd(step, n) !== 1) step++;
  return step;
})();

function hash(value: string): number {
  let h = 0;
  for (let i = 0; i < value.length; i++) h = (h * 31 + value.charCodeAt(i)) >>> 0;
  return h;
}

/** Dias corridos desde 1970 no fuso informado: a frase vira à meia-noite local */
function dayNumber(date: Date, timeZone: string): number {
  const [y, m, d] = new Intl.DateTimeFormat("en-CA", { timeZone, year: "numeric", month: "2-digit", day: "2-digit" })
    .format(date)
    .split("-")
    .map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86_400_000);
}

/** Frase do dia para o usuário: muda à meia-noite e não repete até a biblioteca acabar */
export function getDailyMotivation(userId: string, timeZone: string, date = new Date()): Motivation {
  const n = MOTIVATIONS.length;
  const index = (dayNumber(date, timeZone) * STEP + hash(userId)) % n;
  return MOTIVATIONS[index];
}
